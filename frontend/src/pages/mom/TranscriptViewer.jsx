export default function TranscriptViewer() {
  const [rawText, setRawText] = useState('');
  const [parsed, setParsed] = useState(null);
  const [activeSpeaker, setActiveSpeaker] = useState(null); // null = all
  const [isDragOver, setIsDragOver] = useState(false);
  const fileInputRef = useRef(null);

  // Color map — stable across renders
  const speakerColorMap = useMemo(() => {
    if (!parsed) return {};
    const map = {};
    const seen = new Set();
    parsed.turns.forEach(t => {
      if (t.speaker && !seen.has(t.speaker) && t.type !== 'SYSTEM_ANNOTATION') {
        seen.add(t.speaker);
        const idx = hashName(t.speaker) % SPEAKER_PALETTE.length;
        map[t.speaker] = SPEAKER_PALETTE[idx];
      }
    });
    return map;
  }, [parsed]);

  // Unique speakers for filter bar
  const uniqueSpeakers = useMemo(() => {
    if (!parsed) return [];
    const counts = {};
    parsed.turns.forEach(t => {
      if (t.type === 'SYSTEM_ANNOTATION') return;
      counts[t.speaker] = (counts[t.speaker] || 0) + 1;
    });
    return Object.entries(counts)
      .sort((a, b) => b[1] - a[1])
      .map(([name, count]) => ({ name, count }));
  }, [parsed]);

  // Filtered turns
  const filteredTurns = useMemo(() => {
    if (!parsed) return [];
    if (!activeSpeaker) return parsed.turns;
    return parsed.turns.filter(t =>
      t.speaker === activeSpeaker || t.type === 'SYSTEM_ANNOTATION'
    );
  }, [parsed, activeSpeaker]);

  // Stats
  const stats = useMemo(() => {
    if (!parsed) return null;
    const speechTurns = parsed.turns.filter(t => t.type === 'SPEECH');
    const flagged = parsed.turns.filter(t => t.flags && t.flags.length > 0);
    const continuations = parsed.turns.filter(t => t.type === 'CONTINUATION');
    const systems = parsed.turns.filter(t => t.type === 'SYSTEM_ANNOTATION');
    return {
      totalTurns: speechTurns.length,
      uniqueSpeakers: uniqueSpeakers.length,
      flaggedLines: flagged.length,
      continuations: continuations.length,
      systemAnnotations: systems.length,
      duration: parsed.metadata.duration || null,
    };
  }, [parsed, uniqueSpeakers]);

  // Parse raw text
  const doParse = useCallback((text) => {
    setRawText(text);
    setParsed(parseGoogleMeetTranscript(text));
    setActiveSpeaker(null);
  }, []);

  // Load sample
  const loadSample = useCallback(() => {
    doParse(SAMPLE_TRANSCRIPT);
  }, [doParse]);

  // File upload
  const handleFile = useCallback((file) => {
    if (!file) return;
    const reader = new FileReader();
    reader.onload = (e) => doParse(e.target.result);
    reader.readAsText(file);
  }, [doParse]);

  const handleDrop = (e) => {
    e.preventDefault();
    setIsDragOver(false);
    handleFile(e.dataTransfer?.files?.[0]);
  };

  // Parse participants string into chips
  const participantChips = useMemo(() => {
    if (!parsed?.metadata?.participants) return [];
    return parsed.metadata.participants.split(',').map(p => {
      const raw = p.trim();
      const hostMatch = raw.match(/^(.+?)\s*\(Host\)$/i);
      return {
        name: hostMatch ? hostMatch[1].trim() : raw,
        isHost: !!hostMatch,
      };
    });
  }, [parsed]);

  // ── RENDER ──────────────────────────────────────────────────────────────

  // Pre-load on first mount
  React.useEffect(() => {
    doParse(SAMPLE_TRANSCRIPT);
  }, []);

  return (
    <div className="tv-page">
      <div className="tv-container">

        {/* Breadcrumb */}
        <div className="tv-breadcrumb tv-animate-in">
          <Link to="/dashboard"><Home size={13} /></Link>
          <span className="tv-breadcrumb-sep"><ChevronRight size={11} /></span>
          <Link to="/dashboard/mom">MOM</Link>
          <span className="tv-breadcrumb-sep"><ChevronRight size={11} /></span>
          <span className="tv-breadcrumb-current">Transcript Viewer</span>
        </div>

        {/* Hero */}
        <div className="tv-hero tv-animate-in">
          <div className="tv-hero-badge">
            <Zap size={12} /> Google Meet Parser
          </div>
          <h1>Transcript Viewer</h1>
          <p>Upload a raw Google Meet transcript and see it parsed into a clean, interactive view.</p>
        </div>

        {/* Upload Zone */}
        <div
          className={`tv-upload-zone tv-animate-in ${isDragOver ? 'drag-over' : ''}`}
          onDragOver={e => { e.preventDefault(); setIsDragOver(true); }}
          onDragLeave={() => setIsDragOver(false)}
          onDrop={handleDrop}
          onClick={() => fileInputRef.current?.click()}
        >
          <input
            ref={fileInputRef}
            type="file"
            accept=".txt,.vtt,.srt"
            style={{ display: 'none' }}
            onChange={e => handleFile(e.target.files?.[0])}
          />
          <div className="tv-upload-icon">
            <Upload size={22} />
          </div>
          <div className="tv-upload-title">Drop a .txt transcript here or click to browse</div>
          <div className="tv-upload-sub">Supports Google Meet export format</div>
        </div>

        <div className="tv-upload-or">or use the built-in sample</div>

        <div style={{ textAlign: 'center', marginBottom: 32 }}>
          <button className="tv-sample-btn" onClick={loadSample}>
            <FileText size={14} /> Load Sample Transcript
          </button>
        </div>

        {/* ── Parsed Output ── */}
        {parsed && (
          <>
            {/* Summary Bar */}
            <div className="tv-summary-bar tv-animate-in">
              <div className="tv-stat-card">
                <div className="tv-stat-icon blue"><MessageSquare size={18} /></div>
                <div>
                  <div className="tv-stat-value">{stats.totalTurns}</div>
                  <div className="tv-stat-label">Speech Turns</div>
                </div>
              </div>
              <div className="tv-stat-card">
                <div className="tv-stat-icon green"><Users size={18} /></div>
                <div>
                  <div className="tv-stat-value">{stats.uniqueSpeakers}</div>
                  <div className="tv-stat-label">Speakers</div>
                </div>
              </div>
              <div className="tv-stat-card">
                <div className="tv-stat-icon amber"><AlertTriangle size={18} /></div>
                <div>
                  <div className="tv-stat-value">{stats.flaggedLines}</div>
                  <div className="tv-stat-label">Flagged Lines</div>
                </div>
              </div>
              <div className="tv-stat-card">
                <div className="tv-stat-icon purple"><Clock size={18} /></div>
                <div>
                  <div className="tv-stat-value">{stats.duration || '—'}</div>
                  <div className="tv-stat-label">Duration</div>
                </div>
              </div>
            </div>

            {/* Metadata Card */}
            {Object.keys(parsed.metadata).length > 0 && (
              <div className="tv-meta-card tv-animate-in">
                <div className="tv-meta-title">
                  {parsed.metadata.meeting_title || 'Meeting Transcript'}
                </div>
                <div className="tv-meta-grid">
                  {parsed.metadata.date && (
                    <div className="tv-meta-item">
                      <span className="tv-meta-label">Date</span>
                      <span className="tv-meta-value">{parsed.metadata.date}</span>
                    </div>
                  )}
                  {parsed.metadata.duration && (
                    <div className="tv-meta-item">
                      <span className="tv-meta-label">Duration</span>
                      <span className="tv-meta-value">{parsed.metadata.duration}</span>
                    </div>
                  )}
                  {participantChips.length > 0 && (
                    <div className="tv-meta-item tv-meta-participants">
                      <span className="tv-meta-label">Participants</span>
                      <div className="tv-meta-value">
                        {participantChips.map((p, i) => {
                          const color = speakerColorMap[p.name] || SPEAKER_PALETTE[i % SPEAKER_PALETTE.length];
                          return (
                            <span key={i} className="tv-participant-chip">
                              <span className="tv-participant-avatar" style={{ background: color.bg }}>
                                {getInitials(p.name)}
                              </span>
                              {p.name}
                              {p.isHost && <span className="tv-host-badge">Host</span>}
                            </span>
                          );
                        })}
                      </div>
                    </div>
                  )}
                </div>
              </div>
            )}

            {/* Action Items */}
            {parsed.actions.length > 0 && (
              <div className="tv-actions-card tv-animate-in">
                <div className="tv-actions-header">
                  <CheckCircle2 size={14} />
                  Action Items ({parsed.actions.length})
                </div>
                {parsed.actions.map((a, i) => (
                  <div key={i} className="tv-action-item">
                    <span className="tv-action-owner">{a.owner}</span>
                    <span className="tv-action-dash">—</span>
                    <span className="tv-action-text">{a.text}</span>
                  </div>
                ))}
              </div>
            )}

            {/* Speaker Filter Bar */}
            <div className="tv-filter-bar tv-animate-in">
              <span className="tv-filter-label"><Filter size={11} /> Filter</span>
              <button
                className={`tv-filter-all ${!activeSpeaker ? 'active' : ''}`}
                onClick={() => setActiveSpeaker(null)}
              >
                All
              </button>
              {uniqueSpeakers.map(s => {
                const color = speakerColorMap[s.name] || SPEAKER_PALETTE[0];
                return (
                  <button
                    key={s.name}
                    className={`tv-filter-chip ${activeSpeaker === s.name ? 'active' : ''}`}
                    onClick={() => setActiveSpeaker(activeSpeaker === s.name ? null : s.name)}
                  >
                    <span className="tv-filter-dot" style={{ background: color.bg }} />
                    {s.name}
                    <span style={{ opacity: 0.5, fontSize: 10, marginLeft: 2 }}>({s.count})</span>
                  </button>
                );
              })}
            </div>

            {/* Transcript Feed */}
            <div className="tv-feed">
              {filteredTurns.map((turn, idx) => {
                const color = speakerColorMap[turn.speaker] || SPEAKER_PALETTE[0];
                const isEmpty = turn.flags?.includes('EMPTY_TURN');
                const isUnknown = turn.flags?.includes('UNKNOWN');
                const isUnidentified = turn.flags?.includes('UNIDENTIFIED');
                const isDialIn = turn.flags?.includes('DIAL_IN');
                const showBadge = isUnknown || isUnidentified || isDialIn;

                // System annotation
                if (turn.type === 'SYSTEM_ANNOTATION') {
                  return (
                    <div key={idx} className="tv-turn system-turn">
                      <div className="tv-system-content">
                        <span className="tv-system-tag">System</span>
                        {turn.content}
                      </div>
                    </div>
                  );
                }

                // Continuation
                if (turn.type === 'CONTINUATION') {
                  return (
                    <div key={idx} className="tv-turn continuation">
                      <span className="tv-turn-ts" />
                      <span className="tv-turn-speaker-col" />
                      <div className="tv-turn-content">{turn.content}</div>
                    </div>
                  );
                }

                // Normal speech turn
                return (
                  <React.Fragment key={idx}>
                    {idx > 0 && filteredTurns[idx - 1].type !== 'SYSTEM_ANNOTATION' && turn.type !== 'CONTINUATION' && (
                      <div className="tv-turn-divider" />
                    )}
                    <div className={`tv-turn ${isEmpty ? 'empty-turn' : ''}`}>
                      <span className="tv-turn-ts">{turn.timestamp || ''}</span>
                      <div className="tv-turn-speaker-col">
                        <span className="tv-turn-avatar" style={{ background: color.bg }}>
                          {getInitials(turn.speaker)}
                        </span>
                        <span
                          className="tv-turn-speaker-name"
                          style={{ color: color.bg }}
                          onClick={() => setActiveSpeaker(activeSpeaker === turn.speaker ? null : turn.speaker)}
                        >
                          {turn.speaker}
                          {showBadge && (
                            <span className="tv-badge amber">
                              {isDialIn ? 'Dial-In' : isUnidentified ? 'Unidentified' : 'Unknown'}
                            </span>
                          )}
                        </span>
                      </div>
                      <div className="tv-turn-content">
                        {isEmpty ? (
                          <span className="tv-empty-label">
                            <AlertTriangle size={10} /> Empty Turn
                          </span>
                        ) : (
                          turn.content
                        )}
                      </div>
                    </div>
                  </React.Fragment>
                );
              })}
            </div>

            {/* Footer */}
            <div className="tv-footer">
              Parsed {stats.totalTurns} turns from {stats.uniqueSpeakers} speakers · {stats.flaggedLines} flagged
            </div>
          </>
        )}
      </div>
    </div>
  );
}
