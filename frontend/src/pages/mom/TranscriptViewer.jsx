// PARSER — full spec implementation
// ═══════════════════════════════════════════════════════════════════════════

const RE_TIMESTAMP_LINE = /^\[(\d{1,2}:\d{2}:\d{2})\]\s*(.*)$/;
const RE_PHONE           = /^\+\d[\d\s().…-]{4,}$/;
const RE_SYSTEM_ANNOT    = /^\.{3}(.+)\.{3}$/;
const RE_SEPARATOR       = /^[─═\-_*\s]{3,}$/;
const RE_META_KV         = /^(Meeting title|Date|Duration|Participants)\s*:\s*(.+)/i;
const RE_HEADER_TITLE    = /^Google\s+Meet\s*[-–—]\s*Transcript$/i;
const RE_FOOTER          = /^This transcript was generated by Google Meet\.?$/i;
const RE_MEETING_ENDED   = /^\[?Meeting ended/i;
const RE_ACTION_HEADER   = /^Action items/i;
const RE_ACTION_ITEM     = /^[•·\-*]\s*(.+?)\s*[—–-]\s*(.+)$/;

function parseGoogleMeetTranscript(raw) {
  const lines = raw.split('\n');
  const metadata = {};
  const actions = [];
  const turns = [];

  let lastTimestamp = null;
  let lastSpeaker = null;
  let inActionBlock = false;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.trim();

    // Skip blank lines
    if (!line) continue;

    // Skip separators
    if (RE_SEPARATOR.test(line)) continue;

    // Skip header title
    if (RE_HEADER_TITLE.test(line)) continue;

    // Skip footer
    if (RE_FOOTER.test(line)) continue;

    // Meeting ended line — skip
    if (RE_MEETING_ENDED.test(line)) continue;

    // Action items header
    if (RE_ACTION_HEADER.test(line)) {
      inActionBlock = true;
      continue;
    }

    // Action item bullet
    if (inActionBlock) {
      const am = line.match(RE_ACTION_ITEM);
      if (am) {
        actions.push({ owner: am[1].trim(), text: am[2].trim() });
        continue;
      }
      // If still in action block but not matching, keep scanning
      if (line.startsWith('•') || line.startsWith('·') || line.startsWith('-') || line.startsWith('*')) continue;
      // Non-bullet in action block — leave action block
      inActionBlock = false;
    }

    // Metadata key-value
    const metaMatch = line.match(RE_META_KV);
    if (metaMatch) {
      const key = metaMatch[1].toLowerCase().replace(/\s+/g, '_');
      metadata[key] = metaMatch[2].trim();
      continue;
    }

    // ── RULE 4: System annotation (…text…) ──
    const sysMatch = line.match(RE_SYSTEM_ANNOT);
    if (sysMatch) {
      turns.push({
        type: 'SYSTEM_ANNOTATION',
        timestamp: lastTimestamp,
        speaker: '[SYSTEM]',
        content: sysMatch[1].trim(),
        flags: [],
      });
      continue;
    }

    // ── RULE 1: Check for [HH:MM:SS] bracket ──
    let timestamp = null;
    let remainder = line;

    const tsMatch = line.match(RE_TIMESTAMP_LINE);
    if (tsMatch) {
      timestamp = tsMatch[1];
      lastTimestamp = timestamp;
      remainder = tsMatch[2];
    } else {
      timestamp = lastTimestamp; // inherit
    }

    // ── RULE 4 (no bracket + no colon): continuation or system ──
    if (!tsMatch && !remainder.includes(':')) {
      // No timestamp bracket AND no colon — continuation of previous speaker
      if (turns.length > 0 && turns[turns.length - 1].type !== 'SYSTEM_ANNOTATION') {
        turns.push({
          type: 'CONTINUATION',
          timestamp,
          speaker: lastSpeaker || 'UNKNOWN',
          content: remainder,
          flags: [],
          continuationOf: turns.length - 1,
        });
      }
      continue;
    }

    // ── RULE 2 & 3: Split on FIRST colon for speaker:content ──
    const colonIdx = remainder.indexOf(':');

    let speaker, content;

    if (colonIdx <= 0) {
      // No colon or colon at position 0 — no identifiable speaker
      speaker = 'UNKNOWN';
      content = remainder;
    } else {
      speaker = remainder.slice(0, colonIdx).trim();
      content = remainder.slice(colonIdx + 1).trim();
    }

    // ── Speaker classification ──
    const flags = [];

    if (!speaker || speaker === '') {
      speaker = 'UNKNOWN';
      flags.push('UNKNOWN');
    } else if (speaker === 'Unknown') {
      speaker = 'UNIDENTIFIED';
      flags.push('UNIDENTIFIED');
    } else if (RE_PHONE.test(speaker)) {
      speaker = 'DIAL_IN';
      flags.push('DIAL_IN');
    }

    // ── Content classification ──
    if (!content || content.trim() === '') {
      flags.push('EMPTY_TURN');
    }

    lastSpeaker = speaker;

    turns.push({
      type: 'SPEECH',
      timestamp,
      speaker,
      content: content || '',
      flags,
    });
  }

  return { metadata, actions, turns };
}


